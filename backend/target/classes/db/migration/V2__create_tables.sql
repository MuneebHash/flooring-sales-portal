-- ============================================================
-- FILE STORAGE & ATTACHMENTS
-- ============================================================

CREATE TABLE stored_file (
    stored_file_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name       VARCHAR(255) NOT NULL,
    storage_path    VARCHAR(500) NOT NULL,
    mime_type       VARCHAR(50)  NOT NULL,
    file_size       BIGINT       NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE order_attachment (
    order_attachment_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id             BIGINT          NOT NULL,
    stored_file_id       BIGINT          NOT NULL,
    attachment_kind      attachment_kind NOT NULL,
    created_at           TIMESTAMP       NOT NULL DEFAULT now()
);

-- ============================================================
-- PAYMENTS
-- ============================================================

CREATE TABLE payment_transaction (
    payment_transaction_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                BIGINT         NOT NULL,
    payment_method          payment_method NOT NULL,
    amount                  DECIMAL(10,2)  NOT NULL,
    payment_reference       VARCHAR(100),
    gateway_transaction_id  VARCHAR(100),
    response_status         VARCHAR(50),
    response_message        VARCHAR(255),
    created_at              TIMESTAMP      NOT NULL DEFAULT now()
);

-- ============================================================
-- INVOICES
-- ============================================================

CREATE TABLE invoice (
    invoice_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                BIGINT        NOT NULL,
    version_number          INTEGER       NOT NULL DEFAULT 1,
    invoice_date            DATE          NOT NULL DEFAULT CURRENT_DATE,
    due_date                DATE,
    details_of_sale_snapshot TEXT         NOT NULL,
    sale_price_ex_gst       DECIMAL(10,2) NOT NULL,
    sale_price_inc_gst      DECIMAL(10,2) NOT NULL,
    total_paid              DECIMAL(10,2) NOT NULL,
    balance_due             DECIMAL(10,2) NOT NULL,
    stored_file_id          BIGINT        NOT NULL,
    created_by_user_id      BIGINT        NOT NULL,
    created_at              TIMESTAMP     NOT NULL DEFAULT now()
);