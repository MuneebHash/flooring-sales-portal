-- ============================================================
-- TENANT & ACCESS TABLES
-- ============================================================

CREATE TABLE business (
    business_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(150)  NOT NULL,
    email_domain  VARCHAR(150),
    is_active     BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP     NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP     NOT NULL DEFAULT now()
);

CREATE TABLE store (
    store_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id   BIGINT        NOT NULL,
    name          VARCHAR(150)  NOT NULL,
    store_code    VARCHAR(20)   NOT NULL,
    phone         VARCHAR(20)   NOT NULL,
    email         VARCHAR(150),
    street        VARCHAR(255)  NOT NULL,
    suburb        VARCHAR(100)  NOT NULL,
    state_code    VARCHAR(20)   NOT NULL,
    postcode      VARCHAR(10)   NOT NULL,
    is_active     BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP     NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP     NOT NULL DEFAULT now()
);

CREATE TABLE app_user (
    user_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id       BIGINT        NOT NULL,
    first_name        VARCHAR(100)  NOT NULL,
    last_name         VARCHAR(100)  NOT NULL,
    salesperson_code  VARCHAR(20)   NOT NULL,
    email             VARCHAR(255)  NOT NULL,
    password_hash     VARCHAR(255)  NOT NULL,
    is_active         BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMP     NOT NULL DEFAULT now(),
    updated_at        TIMESTAMP     NOT NULL DEFAULT now()
);

CREATE TABLE user_store_access (
    user_store_access_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id           BIGINT    NOT NULL,
    user_id               BIGINT    NOT NULL,
    store_id              INTEGER   NOT NULL,
    created_at            TIMESTAMP NOT NULL DEFAULT now()
);

-- ============================================================
-- CATALOG TABLES
-- ============================================================

CREATE TABLE store_product (
    product_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        INTEGER        NOT NULL,
    flooring_type   flooring_type  NOT NULL,
    code            VARCHAR(20)    NOT NULL,
    name            VARCHAR(150)   NOT NULL,
    pricing_unit    pricing_unit   NOT NULL,
    price           DECIMAL(10,2)  NOT NULL,
    cost            DECIMAL(10,2)  NOT NULL,
    stock_quantity  DECIMAL(10,2),
    stock_unit      stock_unit,
    is_active       BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at      TIMESTAMP      NOT NULL DEFAULT now()
);

CREATE TABLE store_charge (
    charge_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id       INTEGER        NOT NULL,
    flooring_type  flooring_type  NOT NULL,
    code           VARCHAR(20)    NOT NULL,
    name           VARCHAR(150)   NOT NULL,
    price          DECIMAL(10,2)  NOT NULL,
    cost           DECIMAL(10,2)  NOT NULL,
    is_active      BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at     TIMESTAMP      NOT NULL DEFAULT now()
);

-- ============================================================
-- ORDER HEADER
-- ============================================================

CREATE TABLE sales_order (
    order_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id            BIGINT         NOT NULL,
    store_id               INTEGER        NOT NULL,
    user_id                BIGINT         NOT NULL,
    order_sequence_number  INTEGER        NOT NULL,
    order_number           VARCHAR(50)    NOT NULL,
    flooring_type          flooring_type  NOT NULL,
    order_status           order_status   NOT NULL DEFAULT 'LEAD',
    supply_only            BOOLEAN        NOT NULL DEFAULT FALSE,
    plan_numbers           TEXT,
    proposed_lay_date      DATE,
    lay_date_status        lay_date_status,
    sale_price_ex_gst      DECIMAL(10,2),
    total_cost             DECIMAL(10,2),
    gp                     DECIMAL(10,2),
    gp_percent             DECIMAL(5,2),
    week_number            INTEGER        NOT NULL,
    week_year              INTEGER        NOT NULL,
    details_of_sale        TEXT,
    last_emailed_at        TIMESTAMP,
    created_at             TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at             TIMESTAMP      NOT NULL DEFAULT now()
);

