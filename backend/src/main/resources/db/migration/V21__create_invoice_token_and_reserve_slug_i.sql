-- V21: the order-bound invoice link (invoice_token) and the reserved slug 'i' (Phase 16G PR 4)
--
-- 16G lets the store email the customer a link to the order's latest invoice, which the customer
-- reviews and signs remotely (docs/API-Contracts-Phase16G-Invoice-Link.md sections 7 to 12). The link
-- is a secret token stored only as its SHA-256 lowercase-hex hash, bound to the ORDER (not to one
-- invoice version): every public request resolves the order's current invoice version.
--
-- invoice_token follows the V16 quote_token conventions: BIGINT IDENTITY PK, snake_case, named
-- uq_/fk_/chk_ constraints via ALTER TABLE / CREATE INDEX, NO ON DELETE on the FKs (default
-- RESTRICT), the categorical status as VARCHAR + CHECK. It is a separate table: no shared token table
-- with quote_token, and nothing limits an order to one live link across the quote and invoice
-- surfaces.
--   status      ACTIVE / REPLACED / REWRITTEN / SIGNED / EXPIRED. The status is the dead reason (no
--               separate reason column); a dead row never changes status again.
--   sent_by_user_id  the session user who sent the link; recorded as created_by_user_id on the
--               invoice version this link signs.
--   sent_at     the JVM time of the send transaction that minted the token (stamped before delivery).
--   expires_at  sent_at + 7 days (JVM clock), set by the application.
--   emailed_at  success-only delivery marker for this token's link email (null: delivery failed or
--               not confirmed).
--   dead_at     when the token left ACTIVE.
-- Rows are never deleted: a dead row keeps its status so the public page can show the right message.
-- At most one ACTIVE link per order: the partial unique index below, plus every transition running
-- under the order row lock.
--
-- The second change REPLACES (does not duplicate) the V18 constraint chk_business_slug_reserved for
-- the top-level, slugless public invoice page /i/{token}: a business whose slug equalled 'i' would
-- have every app URL shadowed by it (the V11 / V18 failure class). Every V18 word is kept; the
-- following word is added:
--   i
-- No reserved word is removed. The frontend mirror list (RESERVED_BUSINESS_SLUGS in
-- frontend/src/lib/tenant.ts) is updated in the same change. The seeded slugs
-- (aussie-floors-group, premier-flooring-co) are not in the list.
--
-- Migration policy: V1-V20 are never edited; this is a NEW migration. The CI "Locked migration
-- protection" guard covers V1-V13 only; V14-V21 are outside it, are still never edited, and V21
-- joins every other pre-production migration in the Phase 17 schema-only squash/baseline and its
-- CI re-lock.

-- ============================================================
-- invoice_token — the order-bound public invoice link (never deleted)
-- ============================================================
CREATE TABLE invoice_token (
    invoice_token_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT        NOT NULL,
    token_hash          VARCHAR(255)  NOT NULL,
    status              VARCHAR(16)   NOT NULL,
    sent_by_user_id     BIGINT        NOT NULL,
    sent_at             TIMESTAMP     NOT NULL,
    expires_at          TIMESTAMP     NOT NULL,
    emailed_at          TIMESTAMP,
    dead_at             TIMESTAMP,
    created_at          TIMESTAMP     NOT NULL DEFAULT now()
);

ALTER TABLE invoice_token
    ADD CONSTRAINT fk_invoice_token_order
    FOREIGN KEY (order_id) REFERENCES sales_order (order_id);

ALTER TABLE invoice_token
    ADD CONSTRAINT fk_invoice_token_sent_by
    FOREIGN KEY (sent_by_user_id) REFERENCES app_user (user_id);

ALTER TABLE invoice_token
    ADD CONSTRAINT uq_invoice_token_hash UNIQUE (token_hash);

ALTER TABLE invoice_token
    ADD CONSTRAINT chk_invoice_token_status
    CHECK (status IN ('ACTIVE', 'REPLACED', 'REWRITTEN', 'SIGNED', 'EXPIRED'));

-- At most ONE live (ACTIVE) invoice link per order. A partial unique index counts only ACTIVE rows,
-- so the dead history rows of an order (REPLACED / REWRITTEN / SIGNED / EXPIRED) stay unconstrained.
CREATE UNIQUE INDEX uq_invoice_token_one_active_per_order
    ON invoice_token (order_id)
    WHERE status = 'ACTIVE';

-- ============================================================
-- chk_business_slug_reserved — the 16 V18 words plus 'i'
-- ============================================================
ALTER TABLE business
    DROP CONSTRAINT chk_business_slug_reserved;

ALTER TABLE business
    ADD CONSTRAINT chk_business_slug_reserved
    CHECK (slug NOT IN (
        'admin', 'api', 'login', 'static', 'auth', 'health',
        'dashboard', 'orders', 'select-store', 'assets', 'new',
        'logout', 'account', 'settings', 'public', 'q', 'i'
    ));
